fn in_ranges(table: Ranges, c: char) -> bool {
    let c = c as u32;
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                core::cmp::Ordering::Less
            } else if lo > c {
                core::cmp::Ordering::Greater
            } else {
                core::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Returns true if the given character is an East Asian wide character
/// (Hiragana, Katakana, Han, Hangul, CJK symbols and punctuation, etc).
pub fn is_east_asian_wide_char(c: char) -> bool {
    in_ranges(EAST_ASIAN_WIDE, c)
}

/// Returns true if the given character belongs to the space-discarding character set.
pub fn is_space_discarding_unicode_char(c: char) -> bool {
    in_ranges(SPACE_DISCARDING, c)
}

/// Returns true if the given character is a Hangul character.
pub fn is_hangul_char(c: char) -> bool {
    in_ranges(HANGUL, c)
}

/// East Asian Width property that matters for line break decisions.
/// See <https://www.unicode.org/reports/tr11/tr11-36.html>
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum EastAsianWidth {
    Fullwidth,
    Halfwidth,
    Wide,
    /// Neutral, narrow or ambiguous.
    Other,
}

/// Returns the East Asian Width of the given character.
pub fn east_asian_width(c: char) -> EastAsianWidth {
    if in_ranges(WIDTH_F, c) {
        EastAsianWidth::Fullwidth
    } else if in_ranges(WIDTH_H, c) {
        EastAsianWidth::Halfwidth
    } else if in_ranges(WIDTH_W, c) {
        EastAsianWidth::Wide
    } else {
        EastAsianWidth::Other
    }
}
